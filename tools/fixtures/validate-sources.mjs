#!/usr/bin/env node
// Compare what each source world DECLARES (case lists, generator functions, manifests,
// in-world verification scores) with what it CONTAINS. Writes
// reports/source-validation/SOURCE-VALIDATION-v1.1.{md,json}. Reads source worlds only.
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../lib/archive.mjs';
import { openSource } from '../lib/open.mjs';
import { plain } from '../lib/nbt.mjs';
import { parseSetblocks, generatorFiles } from './zones.mjs';
import { allBlockEntities } from '../families/block_entity.mjs';

const DIM = { 'minecraft:overworld': 0, 'minecraft:the_nether': 1, 'minecraft:the_end': 2 };
const out = { schema: 'mccb.source-validation/1', worlds: {} };
const md = ['# Source validation — MCCB v1.1', '',
  'What each source world declares, against what it contains. Generated by',
  '`tools/fixtures/validate-sources.mjs` from the source worlds only. MCCB evaluates',
  'converters on what the worlds CONTAIN; declared-but-absent content is listed here and',
  'never used as an expectation.', ''];

async function blockAt(src, dim, pos) {
  if (src.edition === 'java') return src.world.blockAt(dim, ...pos);
  const b = src.world.blockAt(DIM[dim], ...pos);
  return b;
}

// Generator-function coverage (how many absolute setblock targets hold the named block)
async function functionCoverage(id, src, kind) {
  const files = generatorFiles(src.rawRoot, kind);
  const sb = parseSetblocks(files);
  const byFile = new Map();
  for (const s of sb) {
    const b = await blockAt(src, s.dim, s.pos);
    const k = s.file.replace(/^.*\//, '');
    const row = byFile.get(k) || { setblock: 0, match: 0, other: 0, air: 0, chunk_absent: 0 };
    row.setblock++;
    if (b === null) row.chunk_absent++;
    else if (b.name === s.block) row.match++;
    else if (/air$/.test(b.name)) row.air++;
    else row.other++;
    byFile.set(k, row);
  }
  return Object.fromEntries([...byFile].sort());
}

for (const id of ['J01@1.1', 'J02@1.0', 'J03@1.0', 'J04@1.0', 'B01@1.0', 'B02@1.0', 'B03@1.0']) {
  const src = await openSource(id);
  const r = { world: id };
  md.push(`## ${id}`, '');
  if (id.startsWith('B01') || id.startsWith('B03')) {
    const pack = fs.readdirSync(path.join(src.rawRoot, 'behavior_packs'))[0];
    const cases = JSON.parse(fs.readFileSync(path.join(src.rawRoot, 'behavior_packs', pack, 'CASES.json'), 'utf8'));
    const tally = { declared: cases.length, with_coordinates: 0, present_non_air: 0, air: 0, chunk_absent: 0, no_coordinates: 0 };
    const absent = [];
    for (const c of cases) {
      if (!Array.isArray(c.coords)) { tally.no_coordinates++; continue; }
      tally.with_coordinates++;
      const dim = /NETHER/.test(c.id) ? 'minecraft:the_nether' : /END/.test(c.id) ? 'minecraft:the_end' : 'minecraft:overworld';
      const b = await blockAt(src, dim, c.coords.map(Math.floor));
      if (b === null) { tally.chunk_absent++; absent.push(c.id); } else if (b.name === 'minecraft:air') tally.air++; else tally.present_non_air++;
    }
    r.declared_cases = tally;
    r.cases_in_absent_chunks = absent;
    r.generator_functions = await functionCoverage(id, src, 'behavior_pack');
    md.push(`Declared cases (pack CASES.json): **${tally.declared}**; with coordinates ${tally.with_coordinates}: ` +
      `non-air block present ${tally.present_non_air}, air ${tally.air}, **chunk absent ${tally.chunk_absent}**; without coordinates ${tally.no_coordinates}.`, '',
      '| Generator function | setblock targets | holding the named block | other block | air | chunk absent |', '|---|---:|---:|---:|---:|---:|');
    for (const [f, v] of Object.entries(r.generator_functions)) md.push(`| ${f} | ${v.setblock} | ${v.match} | ${v.other} | ${v.air} | ${v.chunk_absent} |`);
    md.push('');
  } else if (id.startsWith('B02')) {
    md.push('Hand-built world: no declared case list. Every non-air block above the superflat terrain, every block entity and every actor is a subject.', '');
    r.declared_cases = null;
  } else {
    r.generator_functions = await functionCoverage(id, src, 'datapack');
    const sb = await src.world.savedData('scoreboard');
    const scores = sb ? (plain(sb.tag).data?.PlayerScores || []) : [];
    const pick = (obj, names) => Object.fromEntries(scores.filter((s) => s.Objective === obj && names.includes(s.Name)).map((s) => [s.Name, s.Score ?? 0]));
    if (id.startsWith('J01')) r.in_world_verification = pick('mccb26', ['#certified', '#verify_fail', '#items', '#variants', '#matrix_tiles', '#variants_phys', '#variants_unexpected']);
    if (id.startsWith('J03')) r.in_world_verification = pick('mccb_verify', ['#pass', '#expected', '#verified', '#fail']);
    if (id.startsWith('J04')) r.in_world_verification = pick('mccb_j04_verify', ['#fail']);
    if (id.startsWith('J04')) {
      const bes = await allBlockEntities('java', src.world);
      const books = bes.flatMap((b) => (b.facts.items || []).filter((x) => x.item.written_book)).length;
      r.stations = { books: books, signs: bes.filter((b) => b.facts.sign).length, command_blocks: bes.filter((b) => b.facts.command).length };
    }
    md.push(`In-world verification scores: \`${JSON.stringify(r.in_world_verification || {})}\``, '');
    if (r.stations) md.push(`Stations: ${r.stations.books} books, ${r.stations.signs} signs, ${r.stations.command_blocks} command blocks.`, '');
    if (Object.keys(r.generator_functions).length) {
      md.push('| Build function | setblock targets | holding the named block | other block | air | chunk absent |', '|---|---:|---:|---:|---:|---:|');
      for (const [f, v] of Object.entries(r.generator_functions)) md.push(`| ${f} | ${v.setblock} | ${v.match} | ${v.other} | ${v.air} | ${v.chunk_absent} |`);
      md.push('', '"other block" is expected where a later command of the same generator replaced the block, or where the game changed it (e.g. a lit lamp).', '');
    } else md.push('J01 builds its fixtures with macros and /clone; its boxes come from its own specification/LAYOUT.json (see fixture-rules §2).', '');
  }
  out.worlds[id] = r;
  if (src.world?.cleanup) src.world.cleanup();
}
const dir = path.join(REPO_ROOT, 'reports', 'source-validation');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'SOURCE-VALIDATION-v1.1.json'), JSON.stringify(out, null, 1) + '\n');
fs.writeFileSync(path.join(dir, 'SOURCE-VALIDATION-v1.1.md'), md.join('\n') + '\n');
console.log('wrote reports/source-validation/SOURCE-VALIDATION-v1.1.{md,json}');
