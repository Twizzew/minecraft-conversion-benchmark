// Family "structure" (MCCB v1.3, oracle defect F13 found after the v1.2 freeze): does each
// edition still recognise the structure, by ITS OWN rule, where the source world has one? And
// does a Java chunk whose generation was not finished stay "to be generated"?
// docs/fixture-rules.md §3.9 — rules 50 to 52.
//
// Subjects (built from the SOURCE only):
//   • bedrock_zone (Bedrock source): one per spawn zone on a chunk with terrain — each 0x39
//     area and each 0x77 piece box. Aspect spawn_zone:
//       direct (Java): centre and 8 corners inside a piece of the same structure by the Java
//       rule (rule 50); round trip (Bedrock): the same points covered by a zone of the same
//       mechanism (0x39 same type / 0x77 piece same name).
//   • java_piece (Java source): one per piece of a structure start × decorated chunk it
//     crosses (monument: the building the game rebuilds). Aspect spawn_zone:
//       direct (Bedrock): the centre of piece ∩ chunk covered by a 0x77 piece of the same
//       structure or a 0x39 area of its type (rule 51) — NOT_EVALUATED for structures of which
//       no native Bedrock world of the corpus stores data; round trip (Java): Java rule.
//   • frontier (Java source): per dimension, the chunks whose generation had not reached
//     `features` and that hold no block at all (rule 52). Direct: none written as a finished
//     Bedrock chunk (FinalizedState 2 or any sub-chunk) — such a chunk is never generated by the
//     game and stays a hole in the void. Round trip: none back as a Java chunk at or past
//     `features`. Chunks of the same kind that already hold terrain are NOT_EVALUATED (rule 38:
//     both keeping them half-generated and letting the target generate them are accepted).
import { r, notEvaluated, PASS, PARTIAL, FAIL, NOT_APPLICABLE, REASON } from '../lib/status.mjs';
import {
  JAVA_DIMS, JAVA_TO_SPAWN_TYPE, JAVA_WITH_NATIVE_BEDROCK_DATA, JAVA_STATUS_BEFORE_FEATURES,
  bedrockNameOfJava, bedrockStructureZones, indexZonesByChunk, javaStructureIndex, javaStructureAt, inBox, testPoints,
} from '../lib/structures.mjs';

const DIM_NAME = Object.fromEntries(JAVA_DIMS.map(([n, d]) => [d, n]));
const DIM_NUM = Object.fromEntries(JAVA_DIMS);
const NE_NO_NATIVE = 'NE:no-native-bedrock-structure-data-in-corpus';
const NE_UNREADABLE = 'NE:unreadable-source-structure-record';
const NE_HALF_GENERATED = 'NE:natural-content-in-incomplete-chunk';

export async function enumerate(ctx) {
  const w = ctx.source.world;
  const out = [];
  if (ctx.source.edition === 'bedrock') {
    const { zones, unreadable, terrain } = bedrockStructureZones(w);
    const sorted = zones.slice().sort((a, b) => a.dim - b.dim || a.cx - b.cx || a.cz - b.cz || (a.src < b.src ? -1 : a.src > b.src ? 1 : 0) || a.bb.join(',').localeCompare(b.bb.join(',')));
    for (const z of sorted) {
      const centre = [(z.bb[0] + z.bb[3]) >> 1, (z.bb[1] + z.bb[4]) >> 1, (z.bb[2] + z.bb[5]) >> 1];
      if (!terrain.has(`${z.dim}:${centre[0] >> 4},${centre[2] >> 4}`)) continue; // nothing generated there to judge
      out.push({ family: 'structure', locator: { kind: 'bedrock_zone', dim: DIM_NAME[z.dim] || `dim${z.dim}`, chunk: [z.cx, z.cz], pos: centre },
        expected: { structure: z.id, src: z.src, bedrock: z.src === '0x39' ? { type: z.type } : { name: z.name }, bb: z.bb },
        aspects: { spawn_zone: { direct: 'JAVA_PIECE', roundtrip: 'SAME_MECHANISM' } } });
    }
    for (const u of unreadable) {
      out.push({ family: 'structure', locator: { kind: 'bedrock_unreadable', dim: DIM_NAME[u.dim] || `dim${u.dim}`, chunk: [u.cx, u.cz] },
        expected: { key: u.key }, aspects: { spawn_zone: { direct: NE_UNREADABLE, roundtrip: NE_UNREADABLE } } });
    }
    return out;
  }
  const idx = await javaStructureIndex(w, { keepEmptyFlag: true });
  for (const [dimId, dim] of JAVA_DIMS) {
    const d = idx.get(dim);
    const decorated = (k) => d.statuses.has(k) && !JAVA_STATUS_BEFORE_FEATURES.has(d.statuses.get(k));
    const starts = [...d.chunks].filter(([, e]) => Object.keys(e.starts).length).sort(([a], [b]) => a.localeCompare(b));
    for (const [sk, e] of starts) {
      for (const id of Object.keys(e.starts).sort()) {
        e.starts[id].forEach((bb, piece) => {
          for (let cx = bb[0] >> 4; cx <= bb[3] >> 4; cx++) for (let cz = bb[2] >> 4; cz <= bb[5] >> 4; cz++) {
            if (!decorated(`${cx},${cz}`)) continue;
            const c = [Math.max(bb[0], cx * 16), bb[1], Math.max(bb[2], cz * 16), Math.min(bb[3], cx * 16 + 15), bb[4], Math.min(bb[5], cz * 16 + 15)];
            const p = [(c[0] + c[3]) >> 1, (c[1] + c[4]) >> 1, (c[2] + c[5]) >> 1];
            out.push({ family: 'structure', locator: { kind: 'java_piece', dim: dimId, start_chunk: sk.split(',').map(Number), piece, chunk: [cx, cz], pos: p },
              expected: { structure: id, bedrock: { name: bedrockNameOfJava(id), type: JAVA_TO_SPAWN_TYPE[id] ?? null } },
              aspects: { spawn_zone: { direct: JAVA_WITH_NATIVE_BEDROCK_DATA.has(id) ? 'BEDROCK_ZONE' : NE_NO_NATIVE, roundtrip: 'JAVA_PIECE' } } });
          }
        });
      }
    }
    const proto = [...d.statuses].filter(([, s]) => JAVA_STATUS_BEFORE_FEATURES.has(s)).map(([k]) => k).sort();
    const empty = proto.filter((k) => d.empty.has(k)), withTerrain = proto.filter((k) => !d.empty.has(k));
    const list = (ks) => ks.map((k) => k.split(',').map(Number));
    if (empty.length) out.push({ family: 'structure', locator: { kind: 'frontier', dim: dimId, chunks: 'no-block' },
      expected: { chunks: list(empty) }, aspects: { generation_frontier: { direct: 'LEFT_TO_GENERATE', roundtrip: 'NOT_FINISHED' } } });
    if (withTerrain.length) out.push({ family: 'structure', locator: { kind: 'frontier', dim: dimId, chunks: 'half-generated-terrain' },
      expected: { chunks: list(withTerrain) }, aspects: { generation_frontier: { direct: NE_HALF_GENERATED, roundtrip: NE_HALF_GENERATED } } });
  }
  return out;
}

// Indexes built once per target world (a TargetView), only when a subject needs them.
async function bedrockIndex(view) {
  if (!view._structB) { const z = bedrockStructureZones(view.world); view._structB = { byChunk: indexZonesByChunk(z.zones), world: view.world }; }
  return view._structB;
}
async function javaIndex(view) {
  if (!view._structJ) view._structJ = await javaStructureIndex(view.world);
  return view._structJ;
}

const byShare = (ok, n, rule, evidence) => r(ok === n ? PASS : ok ? PARTIAL : FAIL, rule, { covered: ok, of: n, ...evidence });
const code = (spec, aspect) => (spec.startsWith('NE:') ? notEvaluated(spec.slice(3)) : spec.startsWith('NA:') ? r(NOT_APPLICABLE, `structure.${aspect}.${spec.slice(3)}`) : null);
const opens = (view, aspect) => (view.world ? null : r(FAIL, `structure.${aspect}.world-opens`, { observed: REASON.WORLD_DOES_NOT_OPEN }));

/** Bedrock rule, for a Java piece: covered by a 0x77 piece of the same name or a 0x39 area of its type. */
function bedrockCovers(bidx, dim, exp, p, mechanism = null) {
  for (const z of bidx.byChunk.get(`${dim}|${p[0] >> 4},${p[2] >> 4}`) || []) {
    if (!inBox(p, z.bb)) continue;
    if ((!mechanism || mechanism === '0x77') && z.src === '0x77' && z.name === exp.name) return true;
    if ((!mechanism || mechanism === '0x39') && z.src === '0x39' && exp.type !== null && exp.type !== undefined && z.type === exp.type) return true;
  }
  return false;
}

export async function evaluate(s, ctx) {
  const L = s.locator, A = s.aspects;
  if (L.kind === 'bedrock_unreadable') return { spawn_zone: { direct: code(A.spawn_zone.direct, 'spawn_zone'), roundtrip: code(A.spawn_zone.roundtrip, 'spawn_zone') } };
  if (L.kind === 'bedrock_zone') {
    const pts = testPoints(s.expected.bb);
    const dim = DIM_NUM[L.dim];
    let direct = opens(ctx.direct, 'spawn_zone');
    if (!direct) { const j = await javaIndex(ctx.direct); direct = byShare(pts.filter((p) => javaStructureAt(j, dim, s.expected.structure, p)).length, pts.length, 'structure.spawn_zone.direct.java-rule'); }
    let rt;
    if (!ctx.roundtrip) rt = notEvaluated(REASON.NO_ROUNDTRIP);
    else rt = opens(ctx.roundtrip, 'spawn_zone');
    if (!rt) {
      const b = await bedrockIndex(ctx.roundtrip);
      const exp = s.expected.src === '0x39' ? { name: null, type: s.expected.bedrock.type } : { name: s.expected.bedrock.name, type: null };
      rt = byShare(pts.filter((p) => bedrockCovers(b, dim, exp, p, s.expected.src)).length, pts.length, 'structure.spawn_zone.roundtrip.same-mechanism');
    }
    return { spawn_zone: { direct, roundtrip: rt } };
  }
  if (L.kind === 'java_piece') {
    const dim = DIM_NUM[L.dim];
    let direct = code(A.spawn_zone.direct, 'spawn_zone');
    if (!direct) direct = opens(ctx.direct, 'spawn_zone');
    if (!direct) {
      const b = await bedrockIndex(ctx.direct);
      direct = bedrockCovers(b, dim, s.expected.bedrock, L.pos) ? r(PASS, 'structure.spawn_zone.direct.bedrock-zone') : r(FAIL, 'structure.spawn_zone.direct.bedrock-zone', { observed: 'not-covered' });
    }
    let rt = code(A.spawn_zone.roundtrip, 'spawn_zone');
    if (!rt) rt = !ctx.roundtrip ? notEvaluated(REASON.NO_ROUNDTRIP) : opens(ctx.roundtrip, 'spawn_zone');
    if (!rt) {
      const j = await javaIndex(ctx.roundtrip);
      rt = javaStructureAt(j, dim, s.expected.structure, L.pos) ? r(PASS, 'structure.spawn_zone.roundtrip.java-rule') : r(FAIL, 'structure.spawn_zone.roundtrip.java-rule', { observed: 'not-covered' });
    }
    return { spawn_zone: { direct, roundtrip: rt } };
  }
  // frontier
  const chunks = s.expected.chunks;
  let direct = code(A.generation_frontier.direct, 'generation_frontier');
  if (!direct) direct = opens(ctx.direct, 'generation_frontier');
  if (!direct) {
    const w = ctx.direct.world, dim = DIM_NUM[L.dim];
    let finished = 0, other = 0;
    for (const [cx, cz] of chunks) {
      const t = w.chunkTags(dim, cx, cz);
      if (!t) continue;
      const f = t.get('54');
      if ((f && f.length >= 4 && f.readInt32LE(0) === 2) || [...t.keys()].some((k) => k.startsWith('47:'))) finished++;
      else other++;
    }
    direct = byShare(chunks.length - finished, chunks.length, 'structure.generation_frontier.direct.left-to-generate', { written_as_finished: finished, written_other_keys_only: other });
  }
  let rt = code(A.generation_frontier.roundtrip, 'generation_frontier');
  if (!rt) rt = !ctx.roundtrip ? notEvaluated(REASON.NO_ROUNDTRIP) : opens(ctx.roundtrip, 'generation_frontier');
  if (!rt) {
    const j = await javaIndex(ctx.roundtrip);
    const st = j.get(DIM_NUM[L.dim])?.statuses || new Map();
    const finished = chunks.filter(([cx, cz]) => { const x = st.get(`${cx},${cz}`); return x !== undefined && !JAVA_STATUS_BEFORE_FEATURES.has(x); }).length;
    rt = byShare(chunks.length - finished, chunks.length, 'structure.generation_frontier.roundtrip.not-finished', { back_as_finished: finished });
  }
  return { generation_frontier: { direct, roundtrip: rt } };
}
