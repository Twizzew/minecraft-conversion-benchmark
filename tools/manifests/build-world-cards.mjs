#!/usr/bin/env node
// Generate worlds/<ID>/README.md (one card per world revision) from manifests/worlds.json,
// the fixture files and reports/source-validation/. Nothing on a card is written by hand:
// correct the manifest or the fixtures, then regenerate.
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../lib/archive.mjs';
import { worldsManifest } from '../lib/open.mjs';
import { readFixtures } from '../lib/fixtures-io.mjs';

const worlds = worldsManifest();
const versions = worlds.benchmark_versions;
const sv = (() => { try { return JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'reports', 'source-validation', 'SOURCE-VALIDATION-v1.1.json'), 'utf8')).worlds; } catch { return {}; } })();
const fmt = (n) => Number(n).toLocaleString('en-US');
const dirName = (id) => id.replace('@', '_r');

for (const w of worlds.worlds) {
  if (w.publication_blockers) continue; // no public card for a world whose publication is not decided
  const inVersions = versions.filter((v) => v.worlds.includes(w.id)).map((v) => `${v.version} (${v.status.replace(/_/g, ' ').toLowerCase()})`);
  const L = [];
  L.push(`# ${w.id} — ${w.theme} · ${w.edition === 'java' ? 'Java' : 'Bedrock'} ${w.game_version} · ${w.class}`);
  L.push('');
  L.push('> Generated by `tools/manifests/build-world-cards.mjs` from `manifests/worlds.json`, the fixture file and');
  L.push('> `reports/source-validation/`. Do not edit by hand.');
  L.push('');
  L.push('| | |');
  L.push('|---|---|');
  L.push(`| Status | **${w.status}**${w.superseded_by ? ` (replaced by ${w.superseded_by})` : ''} |`);
  L.push(`| Benchmark versions | ${inVersions.length ? inVersions.join(', ') : 'none'} |`);
  L.push(`| Class | ${w.class} — ${worlds.class_vocabulary[w.class]} |`);
  L.push(`| Level name | \`${w.level_name}\` |`);
  L.push(`| Game version | ${w.edition === 'java' ? `Java ${w.game_version}, DataVersion ${w.data_version}` : `Bedrock ${w.game_version} (minimum client ${w.min_client})`} |`);
  if (w.data_version_notes) L.push(`| DataVersion note | ${w.data_version_notes} |`);
  L.push(`| File | ${w.asset.name ? `\`${w.asset.name}\`` : '— (not distributed)'} (${fmt(w.asset.bytes)} bytes) |`);
  L.push(`| SHA-256 | \`${w.asset.sha256}\` |`);
  L.push(`| Release | ${w.asset.release ? `\`${w.asset.release}\`` : w.status === 'EXPERIMENTAL' ? 'not published (see blockers)' : 'none yet — proposed for `v1.1-source-worlds`, awaiting approval'} |`);
  L.push(`| Frozen | ${w.frozen_at} (evidence: ${w.freeze_evidence}) |`);
  L.push(`| Original filename | \`${w.original_filename}\` |`);
  if (w.predecessor) L.push(`| Predecessor | ${w.predecessor} |`);
  L.push('');
  if (w.revision_reason) { L.push('## Why this revision exists'); L.push(''); L.push(w.revision_reason); L.push(''); }
  L.push('## Provenance');
  L.push('');
  for (const [k, v] of Object.entries(w.provenance || {})) L.push(`- **${k.replace(/_/g, ' ')}**: ${v}`);
  L.push('');
  if (w.publication_blockers) {
    L.push('## Publication blockers');
    L.push('');
    for (const b of w.publication_blockers) L.push(`- ${b}`);
    L.push('');
    L.push('This world is never mixed into a statistic of ACTIVE worlds. Publishing it (or a sanitised derivative) is a decision that has not been taken.');
    L.push('');
  }
  const v = sv[w.id];
  if (v) {
    L.push('## What the source world actually contains (measured)');
    L.push('');
    if (v.generator_functions && Object.keys(v.generator_functions).length) {
      L.push('Absolute-coordinate `setblock` targets of the generator, checked in the frozen world:');
      L.push('');
      L.push('| Generator file | setblock targets | present as written | other block | air | chunk absent |');
      L.push('|---|---:|---:|---:|---:|---:|');
      for (const [f, c] of Object.entries(v.generator_functions)) L.push(`| \`${f}\` | ${c.setblock} | ${c.match} | ${c.other} | ${c.air} | ${c.chunk_absent} |`);
      L.push('');
    }
    if (v.in_world_verification && Object.keys(v.in_world_verification).length) {
      L.push(`In-world verification scores (written by the generator's own verify run): ${Object.entries(v.in_world_verification).map(([k, x]) => `\`${k}\`=${x}`).join(', ')}.`);
      L.push('');
    }
    L.push('Declared cases that are absent from the world are **not** subjects: converters are never judged on content the source does not contain.');
    L.push('');
  }
  let fx = null;
  try { fx = readFixtures(w.id); } catch { /* no fixtures for this revision */ }
  if (fx) {
    L.push('## Fixtures (MCCB v1.1)');
    L.push('');
    L.push(`File \`${fx.file}\` — canonical hash (SHA-256 of the decompressed content) \`${fx.content_sha256}\`, built from source \`${fx.header.source_sha256.slice(0, 16)}…\` by \`${fx.header.generated_by}\` ${fx.header.tools_version}.`);
    L.push('');
    L.push('| Family | Subjects | Assertions |');
    L.push('|---|---:|---:|');
    let s = 0, a = 0;
    for (const [fam, c] of Object.entries(fx.header.families)) { if (!c.subjects) continue; L.push(`| ${fam} | ${fmt(c.subjects)} | ${fmt(c.assertions)} |`); s += c.subjects; a += c.assertions; }
    L.push(`| **total** | **${fmt(s)}** | **${fmt(a)}** |`);
    L.push('');
    L.push(`Each assertion is measured at up to three levels (direct, behaviour, round trip); see [docs/fixture-rules.md](../../docs/fixture-rules.md). Target edition: ${fx.header.target_edition}.`);
    L.push('');
  } else if (w.status === 'SUPERSEDED') {
    L.push('## Fixtures');
    L.push('');
    L.push(`None: a SUPERSEDED revision is never an input of MCCB v1.1. Its file stays byte-identical in its release so that anything measured with it remains checkable.`);
    L.push('');
  }
  L.push('## Results');
  L.push('');
  L.push(fx ? 'Per converter, in `results/<converter>/` (see `manifests/results.json`). Results of different world classes are never added together.' : 'None.');
  L.push('');
  const dir = path.join(REPO_ROOT, 'worlds', dirName(w.id));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'README.md'), L.join('\n'));
  console.log('wrote', path.relative(REPO_ROOT, path.join(dir, 'README.md')));
}
